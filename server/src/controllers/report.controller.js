const { Parser } = require('json2csv');
const PDFDocument = require('pdfkit');
const { getDistributionRecords, getSummaryMetrics } = require('../services/reporting.service');

// GET /api/reports/distributions.csv?from=&to=  (admin only)
const exportCsv = async (req, res) => {
    try {
        const { from, to } = req.query;
        const rows = await getDistributionRecords({ from, to });

        if (rows.length === 0) {
            return res.status(404).json({ error: 'No distribution records found for the given range' });
        }

        const fields = [
            { label: 'Distribution ID', value: 'id' },
            { label: 'Donor Organization', value: 'donor_org' },
            { label: 'Food Type', value: 'food_type' },
            { label: 'Original Quantity', value: 'original_quantity' },
            { label: 'Quantity Distributed', value: 'quantity_distributed' },
            { label: 'Recipient Group', value: 'recipient_group' },
            { label: 'Collected By', value: 'collected_by_volunteer' },
            { label: 'Logged By', value: 'logged_by_admin' },
            { label: 'Distributed At', value: 'distributed_at' },
            { label: 'Notes', value: 'notes' },
        ];

        const parser = new Parser({ fields });
        const csv = parser.parse(rows);

        res.setHeader('Content-Type', 'text/csv');
        res.setHeader('Content-Disposition', `attachment; filename="foodbridge-distributions-${Date.now()}.csv"`);
        res.status(200).send(csv);
    } catch (err) {
        console.error(err);
        res.status(500).json({ error: 'Server error' });
    }
};

// GET /api/reports/distributions.pdf?from=&to=  (admin only)
const exportPdf = async (req, res) => {
    try {
        const { from, to } = req.query;
        const rows = await getDistributionRecords({ from, to });
        const summary = await getSummaryMetrics({ from, to });

        res.setHeader('Content-Type', 'application/pdf');
        res.setHeader('Content-Disposition', `attachment; filename="foodbridge-distributions-${Date.now()}.pdf"`);

        const doc = new PDFDocument({ margin: 40, size: 'A4' });
        doc.pipe(res);

        // --- Header ---
        doc.fontSize(18).font('Helvetica-Bold').text('FoodBridge — Distribution Report', { align: 'center' });
        doc.moveDown(0.3);
        doc.fontSize(9).font('Helvetica').fillColor('#555')
            .text(`Generated: ${new Date().toLocaleString()}`, { align: 'center' })
            .text(`Generated by: ${req.user.name || req.user.id}`, { align: 'center' })
            .text(`Range: ${from || 'all time'} to ${to || 'present'}`, { align: 'center' });
        doc.fillColor('#000').moveDown(1);

        // --- Summary block ---
        doc.fontSize(12).font('Helvetica-Bold').text('Summary');
        doc.fontSize(10).font('Helvetica');
        doc.text(`Total distributions in range: ${rows.length}`);
        doc.text(`Total food posts: ${summary.food_posts.total}`);
        doc.text(`Collection rate: ${summary.rates.collection_rate}%`);
        doc.text(`Waste rate (expired): ${summary.rates.waste_rate}%`);
        doc.moveDown(1);

        // --- Table ---
        doc.fontSize(12).font('Helvetica-Bold').text('Distribution Records');
        doc.moveDown(0.5);

        const tableTop = doc.y;
        const colX = { donor: 40, food: 150, qty: 250, recipient: 320, date: 440 };

        doc.fontSize(9).font('Helvetica-Bold');
        doc.text('Donor', colX.donor, tableTop);
        doc.text('Food', colX.food, tableTop);
        doc.text('Qty', colX.qty, tableTop);
        doc.text('Recipient', colX.recipient, tableTop);
        doc.text('Date', colX.date, tableTop);
        doc.moveDown(0.5);
        doc.moveTo(40, doc.y).lineTo(560, doc.y).stroke();
        doc.moveDown(0.3);

        doc.font('Helvetica').fontSize(8);
        rows.forEach((row) => {
            // Page-break guard — without this, rows silently run off the bottom of the page.
            if (doc.y > 760) {
                doc.addPage();
            }
            const y = doc.y;
            doc.text(row.donor_org || '-', colX.donor, y, { width: 100 });
            doc.text(row.food_type || '-', colX.food, y, { width: 90 });
            doc.text(String(row.quantity_distributed || '-'), colX.qty, y, { width: 60 });
            doc.text(row.recipient_group || '-', colX.recipient, y, { width: 110 });
            doc.text(new Date(row.distributed_at).toLocaleDateString(), colX.date, y, { width: 100 });
            doc.moveDown(0.8);
        });

        doc.end();
    } catch (err) {
        console.error(err);
        if (!res.headersSent) {
            res.status(500).json({ error: 'Server error' });
        }
    }
};

module.exports = { exportCsv, exportPdf };